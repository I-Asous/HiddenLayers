// Small 8×8 pixel icons, drawn as text art ('#' = a pixel). They take the text colour.
function icon(rows) {
  let d = '';
  rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === '#') d += `M${x} ${y}h1v1h-1z`;
  }));
  return `<svg class="px-icon" viewBox="0 0 8 8" shape-rendering="crispEdges" aria-hidden="true"><path
    fill="currentColor" d="${d}"/></svg>`;
}

